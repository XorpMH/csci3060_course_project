from src.user import User
from src.game import Game
from src.backend import applyTransaction
from src.file_handler import readFile, writeFile

import sys


# --------------------------------------------------
# User file functions
# --------------------------------------------------

def loadUsers(file_path):
    """
    Reads the user accounts file and creates User objects.

    Expected format:

    UUUUUUUUUUUUUUU TT CCCCCCCCC

    Username: 15 characters
    Type:      2 characters
    Credit:    9 characters
    """

    users = []

    lines = readFile(file_path)

    for line in lines:
        if len(line) < 28:
            continue

        try:
            username = line[0:15].rstrip()
            user_type = line[16:18].rstrip()
            credit = float(line[19:28])

            if username != "":
                users.append(
                    User(
                        username,
                        user_type,
                        credit
                    )
                )

        except ValueError:
            continue

    return users


def saveUsers(file_path, users):
    """
    Writes the current users to the user accounts file.
    """

    lines = []

    for user in users:
        username = user.get_username()[:15]
        user_type = user.get_user_type()[:2]
        credit = user.get_credit()

        line = (
            f"{username:<15} "
            f"{user_type:<2} "
            f"{credit:09.2f}"
        )

        lines.append(line)

    writeFile(
        file_path,
        lines
    )


# --------------------------------------------------
# Game file functions
# --------------------------------------------------

def loadGames(file_path):
    """
    Reads the available games file and creates Game objects.

    FrontEndC format:

    GAME______________________ SELLER_________ PPPPPP

    Game:   26 characters
    Seller: 15 characters
    Price:   6 characters
    """

    games = []

    lines = readFile(file_path)

    for line in lines:
        if len(line) < 49:
            continue

        try:
            game_name = line[0:26].rstrip()
            seller = line[27:42].rstrip()
            price = float(line[43:49])

            if game_name != "":
                games.append(
                    Game(
                        game_name,
                        seller,
                        price
                    )
                )

        except ValueError:
            continue

    return games


def saveGames(file_path, games):
    """
    Writes the current available games to the game file.
    """

    lines = []

    for game in games:
        game_name = game.get_name()[:26]
        seller = game.get_seller()[:15]
        price = game.get_price()

        line = (
            f"{game_name:<26} "
            f"{seller:<15} "
            f"{price:06.2f}"
        )

        lines.append(line)

    writeFile(
        file_path,
        lines
    )


# --------------------------------------------------
# Backend helpers
# --------------------------------------------------

def findAdministrativeUser(users):
    """
    Finds an AA account to use for administrative
    transactions.

    If no AA account exists, an AM account is used.
    """

    for user in users:
        if user.get_user_type() == "AA":
            return user

    for user in users:
        if user.get_user_type() == "AM":
            return user

    return None


def runBackend(
    transaction_file,
    user_file,
    game_file
):
    """
    Processes every transaction generated by FrontEndC.

    The user and game files are loaded before processing.
    Updated data is written back after all transactions.
    """

    users = loadUsers(user_file)
    games = loadGames(game_file)

    transactions = readFile(
        transaction_file
    )

    if len(transactions) == 0:
        print(
            "No transactions found."
        )

        return False

    print(
        "=== BACKEND TRANSACTION PROCESSING ==="
    )

    print()

    transaction_number = 1

    for transaction in transactions:

        if transaction.strip() == "":
            continue

        current_user = findAdministrativeUser(
            users
        )

        result = applyTransaction(
            transaction,
            current_user,
            users,
            games
        )

        print(
            f"Transaction {transaction_number}: "
            f"{transaction}"
        )

        if result:
            print(
                "Result: SUCCESS"
            )
        else:
            print(
                "Result: FAILURE"
            )

        print()

        transaction_number += 1

    saveUsers(
        user_file,
        users
    )

    saveGames(
        game_file,
        games
    )

    print(
        "Backend processing complete."
    )

    return True


# --------------------------------------------------
# Main program
# --------------------------------------------------

def main():
    """
    Main entry point for the Phase 4 Python backend.

    The backend reads the transaction file produced
    by FrontEndC and updates the user and game files.

    Usage:

    python -m src.frontend

    Or:

    python -m src.frontend transaction_file user_file game_file
    """

    # Default file names
    transaction_file = "daily_transactions.txt"
    user_file = "current_user_accounts.txt"
    game_file = "available_games.txt"

    # Allow file paths to be supplied from command line
    if len(sys.argv) == 4:
        transaction_file = sys.argv[1]
        user_file = sys.argv[2]
        game_file = sys.argv[3]

    print(
        "Phase 4 Python Backend"
    )

    print(
        f"Transaction file: {transaction_file}"
    )

    print(
        f"User file: {user_file}"
    )

    print(
        f"Game file: {game_file}"
    )

    print()

    runBackend(
        transaction_file,
        user_file,
        game_file
    )


if __name__ == "__main__":
    main()